"""Framework-independent dispatch bridge: no new agent runtime or policy engine.

Bindings and the plan must be installed by a trusted host, never generated by an LLM.
The bridge is a cooperative integration; it cannot isolate raw credentials.
"""
from __future__ import annotations

from collections.abc import Callable, Mapping
from hashlib import sha256
import json
from dataclasses import dataclass
from typing import Any

from ..coherence import CoherenceAnalyzer, ConstitutionalPlan
from ..gateway import ConstitutionalGateway
from ..models import ActionIntent, ExecutionReceipt, Verdict


@dataclass(frozen=True)
class BoundTool:
    name: str
    intent_from_args: Callable[[Mapping[str, Any]], ActionIntent]
    step_id: str | None = None
    expected_args_digest: str | None = None  # required for governed plan dispatch


@dataclass(frozen=True)
class BrokerResult:
    executed: bool
    code: str
    result: Any = None
    receipt: ExecutionReceipt | None = None


def canonical_args_digest(args: Mapping[str, Any]) -> str:
    payload = json.dumps(dict(args), sort_keys=True, ensure_ascii=False,
                         separators=(",", ":"), allow_nan=False).encode("utf-8")
    return sha256(payload).hexdigest()


class ConstitutionalToolBroker:
    def __init__(self, gateway: ConstitutionalGateway, bindings: tuple[BoundTool, ...],
                 plan: ConstitutionalPlan | None = None,
                 analyzer: CoherenceAnalyzer | None = None):
        names = [b.name for b in bindings]
        if any(not n for n in names) or len(set(names)) != len(names):
            raise ValueError("Tool names must be distinct and nonempty")
        if (plan is None) != (analyzer is None):
            raise ValueError("A plan must have a matching coherence analyzer")
        self.gateway = gateway
        self.bindings = {b.name: b for b in bindings}
        self.plan = plan
        self.analyzer = analyzer
        if plan is not None:
            for b in bindings:
                if b.step_id is None or b.step_id not in {s.step_id for s in plan.steps}:
                    raise ValueError("Every bound tool must reference an existing plan step")
                if b.expected_args_digest is None:
                    raise ValueError("Plan-bound tools must bind the canonical arguments digest")

    def _deny(self, name: str, code: str) -> BrokerResult:
        # Fail closed if the audit sink is unavailable.
        self.gateway.audit.append("framework_tool_refused", {"tool": name, "code": code})
        return BrokerResult(False, code)

    def invoke(self, name: str, args: Mapping[str, Any],
               operation: Callable[[], Any]) -> BrokerResult:
        binding = self.bindings.get(name)
        if binding is None:
            return self._deny(name, "tool_not_registered")
        try:
            intent = binding.intent_from_args(args)
            if not isinstance(intent, ActionIntent):
                return self._deny(name, "invalid_intent_mapping")
        except (TypeError, KeyError, ValueError) as exc:
            return self._deny(name, "invalid_tool_arguments")
        if self.plan is not None:
            try:
                observed_digest = canonical_args_digest(args)
            except (TypeError, ValueError):
                return self._deny(name, "arguments_not_canonical_json")
            if observed_digest != binding.expected_args_digest:
                return self._deny(name, "arguments_differ_from_governed_plan")
            expected = next(s.intent for s in self.plan.steps if s.step_id == binding.step_id)
            if intent != expected:
                return self._deny(name, "intent_differs_from_governed_plan")
            assert self.analyzer is not None
            assessment = self.analyzer.assess(self.plan)
            if not assessment.admissible:
                return self._deny(name, f"plan_{assessment.verdict.value.lower()}")
        receipt = self.gateway.execute(intent, operation)
        if not receipt.executed:
            return BrokerResult(False, receipt.decision.verdict.value.lower(), receipt=receipt)
        if receipt.outcome == "failed":
            return BrokerResult(True, "tool_failed", receipt=receipt)
        return BrokerResult(True, "completed", result=receipt.result, receipt=receipt)
